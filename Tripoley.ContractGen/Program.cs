using System.Collections;
using System.Reflection;
using System.Text;
using Tripoley.Api.Contracts;
using Tripoley.Api.Hubs;

const string ContractsNamespace = "Tripoley.Api.Contracts";

var nullability = new NullabilityInfoContext();
var enums = new SortedDictionary<string, Type>(StringComparer.Ordinal);
var records = new SortedDictionary<string, Type>(StringComparer.Ordinal);

foreach (Type seed in typeof(CardDto).Assembly.GetTypes()
    .Where(type => type.Namespace == ContractsNamespace && IsRecord(type)))
{
    Collect(seed);
}

var output = new StringBuilder();
output.AppendLine("// Generated by Tripoley.ContractGen. Do not edit by hand.");
output.AppendLine("// Run: dotnet run --project Tripoley.ContractGen -- tripoley-web/src/api/contracts.ts");
output.AppendLine();

foreach (Type enumType in enums.Values)
{
    string members = string.Join(" | ", Enum.GetNames(enumType).Select(name => $"\"{name}\""));
    output.AppendLine($"export type {enumType.Name} = {members};");
    output.AppendLine();
}

foreach (Type record in records.Values)
{
    output.AppendLine($"export interface {record.Name} {{");
    foreach (ParameterInfo parameter in PrimaryConstructor(record).GetParameters())
        output.AppendLine($"  {CamelCase(parameter.Name!)}: {TsType(parameter)};");
    output.AppendLine("}");
    output.AppendLine();
}

output.AppendLine(ConstMap("ServerEvents", typeof(ClientEvents)
    .GetFields(BindingFlags.Public | BindingFlags.Static)
    .Where(field => field.IsLiteral)
    .ToDictionary(field => field.Name, field => (string)field.GetRawConstantValue()!)));
output.AppendLine();

output.AppendLine(ConstMap("HubMethods", typeof(GameHub)
    .GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
    .Where(method => !method.IsSpecialName && !IsLifecycleHook(method.Name))
    .Select(method => method.Name)
    .Distinct(StringComparer.Ordinal)
    .OrderBy(name => name, StringComparer.Ordinal)
    .ToDictionary(name => name, name => name)));

string text = output.ToString().ReplaceLineEndings("\n");

if (args.Length > 0)
    File.WriteAllText(args[0], text);
else
    Console.Out.Write(text);

return;

void Collect(Type type)
{
    if (type.IsEnum)
    {
        enums.TryAdd(type.Name, type);
        return;
    }
    if (!IsRecord(type) || records.ContainsKey(type.Name))
        return;

    records.Add(type.Name, type);
    foreach (ParameterInfo parameter in PrimaryConstructor(type).GetParameters())
        Collect(CoreType(parameter.ParameterType));
}

string TsType(ParameterInfo parameter)
{
    NullabilityInfo info = nullability.Create(parameter);
    bool nullable = Nullable.GetUnderlyingType(parameter.ParameterType) is not null
        || info.ReadState == NullabilityState.Nullable;
    string ts = Scalar(parameter.ParameterType) is { } scalar
        ? scalar
        : $"{Scalar(CoreType(parameter.ParameterType)) ?? CoreType(parameter.ParameterType).Name}[]";
    return nullable ? $"{ts} | null" : ts;
}

string? Scalar(Type type)
{
    Type core = Nullable.GetUnderlyingType(type) ?? type;
    if (ElementType(core) is not null) return null;
    if (core == typeof(string) || core == typeof(Guid)) return "string";
    if (core == typeof(bool)) return "boolean";
    if (core.IsEnum) return core.Name;
    if (core.IsPrimitive || core == typeof(decimal)) return "number";
    if (IsRecord(core)) return core.Name;
    throw new NotSupportedException($"No TypeScript mapping for {core}.");
}

Type CoreType(Type type)
{
    Type unwrapped = Nullable.GetUnderlyingType(type) ?? type;
    return ElementType(unwrapped) ?? unwrapped;
}

static Type? ElementType(Type type)
{
    if (type.IsArray) return type.GetElementType();
    if (type == typeof(string)) return null;
    if (!type.IsGenericType || !typeof(IEnumerable).IsAssignableFrom(type)) return null;
    return type.GetGenericArguments()[0];
}

static ConstructorInfo PrimaryConstructor(Type record) =>
    record.GetConstructors().OrderByDescending(ctor => ctor.GetParameters().Length).First();

static bool IsRecord(Type type) =>
    type.GetMethod("<Clone>$", BindingFlags.Public | BindingFlags.Instance) is not null;

static bool IsLifecycleHook(string name) =>
    name is "OnConnectedAsync" or "OnDisconnectedAsync";

static string CamelCase(string name) => char.ToLowerInvariant(name[0]) + name[1..];

static string ConstMap(string name, IReadOnlyDictionary<string, string> entries)
{
    var builder = new StringBuilder();
    builder.AppendLine($"export const {name} = {{");
    foreach ((string key, string value) in entries)
        builder.AppendLine($"  {key}: \"{value}\",");
    builder.Append("} as const;");
    return builder.ToString();
}
